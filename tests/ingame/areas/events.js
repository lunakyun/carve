// Events area: every player/server event a test bot can cause.
//   node tests/ingame/areas/events.js
'use strict'
const fs = require('fs')
const path = require('path')
const { area } = require('../lib/area.js')
const { startServer } = require('../lib/server.js')
const { joinBot } = require('../lib/bot.js')
const { statusPing } = require('../lib/status.js')

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
// A start time for the next wait. +1 ms: a reply that resolved the previous
// wait can carry the same millisecond and would match again.
const now = () => Date.now() + 1
const t = area('events', { port: 25571 })
const SCRIPTS = [path.join(__dirname, 'events', 'events.carve')]

t.run(async () => {
  // `on first join` remembers players in first_join.txt; start from nobody.
  fs.rmSync(path.join(t.dir, 'plugins', 'data', 'carve', 'first_join.txt'), { force: true })
  const srv = await startServer({ dir: t.dir, port: t.port, scripts: SCRIPTS, ops: ['Tester'] })
  t.cleanup(async () => t.check('server stops cleanly', await srv.stop()))
  const loadErr = srv.lines.find((l) => /\[Carve\].*(error|Error)/.test(l))
  t.check('script loads without errors', !!await srv.waitLog(/\[Carve\] Loaded 1 script/, 3000) && !loadErr, loadErr || '')
  t.check('on load runs at start', !!await srv.waitLog(/e:load/, 3000))

  // ---- join, first join, quit ----
  const bot = await joinBot('Tester', { port: t.port })
  t.cleanup(() => bot.quit())
  t.check('on join + player', !!await bot.waitText('e:join Tester'))
  t.check('on first join (new player)', !!await bot.waitText('e:first Tester'))
  let pleb = await joinBot('Pleb', { port: t.port })
  t.check('on first join (second new player)', !!await pleb.waitText('e:first Pleb'))
  let since = now()
  pleb.quit()
  t.check('on quit + player name', !!await bot.waitText('e:quit Pleb', { since }))
  since = now()
  pleb = await joinBot('Pleb', { port: t.port })
  t.cleanup(() => pleb.quit())
  t.check('on join again', !!await pleb.waitText('e:join Pleb', { since }))
  t.check('on first join does not fire twice', !await pleb.waitText('e:first Pleb', { since, ms: 1500 }))

  // ---- chat ----
  since = now()
  bot.chat('hello there')
  t.check('on chat + message', !!await bot.waitText('e:chat hello there', { since }))
  t.check('uncancelled chat reaches others', !!await pleb.waitText('hello there', { since, kind: 'chat' }))
  since = now()
  bot.chat('e-cancel')
  t.check('on chat cancel: script runs', !!await bot.waitText('e:chat-cancelled', { since }))
  t.check('on chat cancel: message not delivered', !await pleb.waitText('e-cancel', { since, ms: 1500 }))

  // ---- command event ----
  since = now()
  bot.command('eblocked now')
  t.check('on command + full command + cancel', !!await bot.waitText('e:cmd-cancel eblocked now', { since }))
  t.check('cancelled command does not run', !await bot.waitText('e:eblocked-ran', { since, ms: 1500 }))
  since = now()
  bot.command('eplain foo bar')
  const cmd = await bot.waitText('e:cmd ', { since })
  t.check('on command "name": command / full command', !!cmd && cmd.text.includes('e:cmd eplain | eplain foo bar'), cmd ? cmd.text : 'none')
  t.check('uncancelled command runs', !!await bot.waitText('e:eplain-ran foo bar', { since }))

  // ---- setup: creative at a known spot ----
  const flag = async (name, on = true) => {
    const s = now()
    bot.command(`${on ? 'eflag' : 'eunflag'} ${name}`)
    await bot.waitText(`e:${on ? 'flag' : 'unflag'} ${name}`, { since: s })
  }
  const tpTo = async (x, y, z) => {
    const s = now()
    srv.console(`tp Tester ${x} ${y} ${z}`)
    await bot.waitFor((e) => e.kind === 'position' && e.text === `${x} ${y} ${z}`, 4000, s)
    await sleep(200)
  }
  srv.console('gamemode creative Tester')
  await bot.waitPacket('game_event', (d) => d.gameMode === 'creative')
  await tpTo(0.5, 64, 0.5)

  // ---- move ----
  await flag('move')
  since = now()
  await bot.walkTo(2.5, 64, 0.5)
  const mv = await bot.waitText('e:move 1', { since })
  t.check('on move + event-location + past event-location', !!mv && /e:move 1(\.\d+)? 0(\.\d+)? from 0(\.\d+)? 0/.test(mv.text), mv ? mv.text : 'none')
  await flag('move', false)
  since = now()
  bot.look(45, 10)
  t.check('on move ignores turning the head', !await bot.waitText('e:move', { since, ms: 800 }))

  // ---- toggles ----
  since = now()
  bot.sneak(true)
  const sn = await bot.waitText('e:sneak', { since })
  t.check('on sneak toggle (start)', !!sn, sn ? sn.text : 'none')
  await sleep(300) // Pumpkin updates the sneaking flag a tick after the event
  since = now()
  bot.sneak(false)
  const sn2 = await bot.waitText('e:sneak', { since })
  t.check('on sneak toggle (stop)', !!sn2, sn2 ? sn2.text : 'none')
  t.check('player is sneaking differs between start and stop', !!sn && !!sn2 && sn.text !== sn2.text, `${sn && sn.text} / ${sn2 && sn2.text}`)
  since = now()
  bot.sprint(true)
  t.check('on sprint toggle', !!await bot.waitText('e:sprint', { since }))
  bot.sprint(false)
  since = now()
  bot.fly(true)
  t.check('on flight toggle', !!await bot.waitText('e:flight', { since }))
  bot.fly(false)
  // Pleb sees Tester's hands change through set_equipment.
  srv.console('clear Tester')
  since = now()
  srv.console('give Tester stick 1')
  await bot.waitPacket('container_set_slot', (d) => d.item && d.item.name === 'stick', 4000, since)
  bot.setHotbar(0)
  await sleep(300)
  const handsOf = (since) => pleb.waitPacket('set_equipment', (d) => d.entityId === bot.entityId && 'offhand' in d.slots, 1500, since)
  since = now()
  bot.swapHands()
  t.check('on swap hand items', !!await bot.waitText('e:swap', { since }))
  t.check('uncancelled swap moves the item', !!await handsOf(since))
  await flag('swapcancel')
  since = now()
  bot.swapHands()
  t.check('on swap hand items cancel: script runs', !!await bot.waitText('e:swap-cancelled', { since }))
  t.check('on swap hand items cancel: hands stay', !await handsOf(since))
  await flag('swapcancel', false)

  // ---- teleport and world change ----
  await flag('tp')
  since = now()
  srv.console('tp Tester 10 64 10')
  const tp = await bot.waitText('e:tp 10', { since })
  t.check('on teleport + event-location + past event-location', !!tp && /e:tp 10\.5 64 from 2\.5/.test(tp.text), tp ? tp.text : 'none')
  since = now()
  srv.console('tp Tester 77 64 0')
  t.check('on teleport cancel: script runs', !!await bot.waitText('e:tp-cancelled', { since }))
  t.check('on teleport cancel: no move to x 77', !await bot.waitFor((e) => e.kind === 'position' && e.text.startsWith('77 '), 1500, since))
  await flag('tp', false)
  since = now()
  srv.console('execute in minecraft:the_nether run tp Tester 0 100 0')
  const wc = await bot.waitText('e:world', { since, ms: 6000 })
  t.check('on world change + event-world + past event-world', !!wc && /e:world minecraft:the_nether from world/.test(wc.text), wc ? wc.text : 'none')
  const wop = await bot.waitText('e:wop', { since })
  t.check('world of player matches event-world', !!wop && wop.text.includes('e:wop minecraft:the_nether'), wop ? wop.text : 'none')
  await sleep(500)
  since = now()
  srv.console('execute in minecraft:overworld run tp Tester 0.5 64 0.5')
  await bot.waitText('e:world', { since, ms: 6000 })
  await sleep(500)
  await tpTo(0.5, 64, 0.5)

  // ---- clicks ----
  srv.console('setblock 2 64 0 minecraft:gold_block')
  srv.console('setblock 0 64 2 minecraft:emerald_block')
  srv.console('clear Tester')
  since = now()
  srv.console('give Tester stick 1')
  await bot.waitPacket('container_set_slot', (d) => d.item && d.item.name === 'stick', 4000, since)
  bot.setHotbar(0)
  await sleep(300)
  // Look straight up: the world is new each run, and a tree in view would be
  // the clicked block of an air click.
  bot.look(0, -90)
  since = now()
  bot.useItem()
  const rcs = await bot.waitText('e:rclick-stick', { since })
  t.check('on right click with stick (air) + clicked block', !!rcs && rcs.text.includes('air'), rcs ? rcs.text : 'none')
  t.check('on consume does not fire for a stick', !await bot.waitText('e:consume', { since, ms: 800 }))
  since = now()
  bot.useOn(2, 64, 0, 4)
  t.check('on right click on gold block', !!await bot.waitText('e:rclick-on-gold', { since }))
  const rcs2 = await bot.waitText('e:rclick-stick gold', { since })
  t.check('clicked block is the block clicked', !!rcs2, rcs2 ? rcs2.text : 'none')
  srv.console('gamemode survival Tester')
  await bot.waitPacket('game_event', (d) => d.gameMode === 'survival', 4000, since)
  since = now()
  bot.breakBlock(0, 64, 2, { finish: false })
  const lc = await bot.waitText('e:lclick-stick-emerald', { since })
  t.check('on left click with stick on emerald block + event-block', !!lc && lc.text.includes('emerald'), lc ? lc.text : 'none')
  bot.send('player_action', Buffer.from([2]), Buffer.alloc(8), [0], Buffer.from([0])) // cancel digging (26.3 id 2)
  since = now()
  bot.breakBlock(2, 64, 0, { finish: false })
  t.check('left click filter: other block does not match', !await bot.waitText('e:lclick-stick-emerald', { since, ms: 1000 }))
  bot.send('player_action', Buffer.from([2]), Buffer.alloc(8), [0], Buffer.from([0]))
  await flag('click')
  since = now()
  bot.useItem()
  t.check('on click (either button)', !!await bot.waitText('e:click-any', { since }))
  await flag('click', false)
  await flag('lclick')
  since = now()
  bot.breakBlock(2, 64, 0, { finish: false })
  const lc2 = await bot.waitText('e:lclick', { since })
  t.check('on left click on a block + clicked block', !!lc2 && lc2.text.includes('gold'), lc2 ? lc2.text : 'none')
  bot.send('player_action', Buffer.from([2]), Buffer.alloc(8), [0], Buffer.from([0]))
  await flag('lclick', false)
  since = now()
  srv.console('clear Tester')
  await sleep(300)
  bot.useItem()
  t.check('right click with filter: empty hand does not match', !await bot.waitText('e:rclick-stick', { since, ms: 1000 }))

  // ---- break / place (+ cancel) ----
  srv.console('gamemode creative Tester')
  await bot.waitPacket('game_event', (d) => d.gameMode === 'creative', 4000, since)
  // Spawn protection only lets ops (level 4, from ops.json) build here.
  await tpTo(0.5, 64, 0.5)
  // A chunk may still be loading after a teleport; retry until setblock works.
  const setblock = async (x, y, z, block) => {
    for (let i = 0; i < 40; i++) {
      const m = srv.mark()
      srv.console(`setblock ${x} ${y} ${z} minecraft:${block}`)
      const r = await srv.waitLog(/Changed the block|not loaded|Could not set/, 2000, m)
      if (r && !/not loaded/.test(r)) return true
      await sleep(250)
    }
    return false
  }
  t.check('setblock for the break test', await setblock(3, 64, 1, 'stone'))
  await setblock(3, 64, 0, 'stone')
  await flag('break')
  since = now()
  bot.breakBlock(3, 64, 1)
  t.check('on break', !!await bot.waitText('e:break', { since }))
  const gone = await bot.waitPacket('block_update', (d) => d.x === 3 && d.y === 64 && d.z === 1, 3000, since)
  t.check('uncancelled break removes the block', !!gone && gone.block === 'air', gone ? gone.block : 'none')
  await setblock(3, 64, 1, 'stone')
  await flag('cancel')
  since = now()
  bot.breakBlock(3, 64, 1)
  t.check('on break cancel: script runs', !!await bot.waitText('e:break-cancelled', { since }))
  const back = await bot.waitPacket('block_update', (d) => d.x === 3 && d.y === 64 && d.z === 1, 3000, since)
  t.check('on break cancel: block stays', !back || back.block === 'stone', back ? back.block : 'no update')
  await flag('break', false)
  await flag('place')
  since = now()
  srv.console('give Tester stone 4')
  await bot.waitPacket('container_set_slot', (d) => d.item && d.item.name === 'stone', 4000, since)
  bot.setHotbar(0)
  await sleep(200)
  since = now()
  bot.place(3, 65, 1)
  t.check('on place cancel: script runs', !!await bot.waitText('e:place-cancelled', { since }))
  const pc = await bot.waitPacket('block_update', (d) => d.x === 3 && d.y === 65 && d.z === 1, 2000, since)
  t.check('on place cancel: no block placed', !pc || pc.block === 'air', pc ? pc.block : 'no update')
  await flag('cancel', false)
  since = now()
  bot.place(3, 65, 1)
  t.check('on place', !!await bot.waitText('e:place', { since }))
  const pl = await bot.waitPacket('block_update', (d) => d.x === 3 && d.y === 65 && d.z === 1 && d.block === 'stone', 2000, since)
  t.check('uncancelled place puts the block', !!pl)
  await flag('place', false)

  // ---- drop / pick up / consume ----
  srv.console('gamemode survival Tester')
  srv.console('clear Tester')
  await sleep(300)
  since = now()
  srv.console('give Tester dirt 2')
  await bot.waitPacket('container_set_slot', (d) => d.item && d.item.name === 'dirt', 4000, since)
  bot.setHotbar(0)
  // Stand on a block and look straight down so the item lands at the bot's feet.
  await setblock(0, 63, 0, 'stone')
  await tpTo(0.5, 64, 0.5)
  bot.look(0, 90)
  await sleep(200)
  since = now()
  bot.dropItem()
  const dr = await bot.waitText('e:drop', { since })
  t.check('on drop + event-item', !!dr && dr.text.includes('dirt'), dr ? dr.text : 'none')
  const item = await bot.waitPacket('add_entity', (d) => d.type === 'item', 3000, since)
  t.check('uncancelled drop spawns an item entity', !!item)
  // The bot has no physics: walk onto the item after its 2 s pickup delay.
  let pu = await bot.waitText('e:pickup', { since, ms: 2500 })
  if (!pu && item) {
    const back = { ...bot.pos }
    await bot.walkTo(item.x, item.y, item.z, 0.3)
    pu = await bot.waitText('e:pickup', { since, ms: 4000 })
    await bot.walkTo(back.x, back.y, back.z, 0.3)
  }
  t.check('on pick up', !!pu, pu ? pu.text : 'none')
  if (pu && pu.text.includes('dirt')) t.check('on pick up: event-item', true, pu.text)
  else if (pu) t.skip('on pick up: event-item', `Pumpkin 0.2.2 sends the entity type id, not the item (${pu.text})`)
  srv.console('clear Tester')
  await sleep(300)
  since = now()
  srv.console('give Tester diamond 1')
  await bot.waitPacket('container_set_slot', (d) => d.item && d.item.name === 'diamond', 4000, since)
  await sleep(200)
  since = now()
  bot.dropItem()
  t.check('on drop cancel: script runs', !!await bot.waitText('e:drop-cancelled', { since }))
  t.check('on drop cancel: no item entity', !await bot.waitPacket('add_entity', (d) => d.type === 'item', 1500, since))
  srv.console('clear Tester')
  await sleep(300)
  since = now()
  srv.console('give Tester bread 2')
  await bot.waitPacket('container_set_slot', (d) => d.item && d.item.name === 'bread', 4000, since)
  srv.console('effect give Tester minecraft:hunger 5 50')
  await sleep(2000)
  since = now()
  bot.useItem()
  const cs = await bot.waitText('e:consume', { since })
  t.check('on consume + event-item', !!cs && cs.text.includes('bread'), cs ? cs.text : 'none')
  srv.console('effect clear Tester')
  srv.console('clear Tester')

  // ---- respawn ----
  since = now()
  srv.console('kill Tester')
  await bot.waitFor((e) => e.kind === 'health' && Number(e.text) <= 0, 4000, since)
  await sleep(300)
  since = now()
  bot.respawn()
  t.check('on respawn', !!await bot.waitText('e:respawn', { since }))
  await sleep(500)

  // ---- timers ----
  await flag('every')
  since = now()
  const ev1 = await bot.waitText('e:every', { since, ms: 6000 })
  const ev2 = ev1 && await bot.waitText('e:every', { since: Date.now() + 100, ms: 6000 })
  t.check('every 2 seconds fires repeatedly', !!ev1 && !!ev2)
  await flag('every', false)
  since = now()
  srv.console('time set 11940')
  t.check('at 18:00 fires when the clock reaches it', !!await bot.waitText('e:at-18', { since, ms: 8000 }))
  since = now()
  t.check('at 18:00 fires only once', !await bot.waitText('e:at-18', { since, ms: 1500 }))

  // ---- inventory click / close (own inventory, window 0) ----
  await flag('inv')
  since = now()
  bot.clickSlot(36)
  const ic = await bot.waitText('e:invclick', { since })
  t.check('on inventory click + clicked slot', !!ic && ic.text.includes('36'), ic ? ic.text : 'none')
  since = now()
  bot.closeContainer(0)
  t.check('on inventory close', !!await bot.waitText('e:invclose', { since }))
  await flag('inv', false)

  // ---- server list ping ----
  try {
    const st = await statusPing(t.port)
    const motd = JSON.stringify(st.description)
    t.check('on server list ping: set event-motd + event-players', motd.includes('e:motd 2'), motd)
    t.check('on server list ping: set event-max-players', st.players && st.players.max === 42, JSON.stringify(st.players))
  } catch (e) {
    t.check('on server list ping', false, e.message)
  }

  // ---- kick ----
  since = now()
  srv.console('kick Pleb nokick please')
  t.check('on kick + event-text', !!await bot.waitText('e:kick Pleb nokick please', { since }))
  await sleep(1000)
  t.check('on kick cancel keeps the player', !pleb.closed && !await pleb.waitText('nokick', { kind: 'kick', since, ms: 200 }))
  since = now()
  srv.console('kick Pleb bye now')
  t.check('on kick (uncancelled)', !!await bot.waitText('e:kick Pleb bye now', { since }))
  // The disconnect packet can be lost when Pumpkin closes the socket right after it.
  const kicked = await pleb.waitText('bye now', { kind: 'kick', since, ms: 3000 })
  t.check('uncancelled kick disconnects', !!kicked || pleb.closed)

  await sleep(300)
  t.check('bot still connected after all events', !bot.closed)
  const errs = srv.lines.filter((l) => /panic|\[Carve\].*(error|failed)/i.test(l))
  t.check('no Carve errors or panics in the log', errs.length === 0, errs.slice(0, 3).join(' | '))
})
