//! Metadata for the generated syntax reference (`examples/gen_docs.rs`).
//!
//! Nothing here is used by the compiler or the engine. Effects and conditions
//! come from the pattern registries; this file only adds names, descriptions
//! and examples, keyed by the exact registry pattern text. Syntax that is
//! parsed by hand (expressions, events, most world and list forms) is listed
//! here with its patterns. A registry pattern with no entry still shows up in
//! the reference, without a description.
//!
//! Examples are checked by a test: an example that does not start with a
//! top-level line (`on`, `command`, `every`, `function`, `options`) is wrapped
//! in `on join:` and must compile.

/// Reference page an entry belongs to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Cat {
    Event,
    Effect,
    Condition,
    Expression,
    Type,
    Function,
}

impl Cat {
    pub const ALL: [Cat; 6] = [
        Cat::Event,
        Cat::Effect,
        Cat::Condition,
        Cat::Expression,
        Cat::Type,
        Cat::Function,
    ];

    /// Singular name, also the `category` field in `syntax.json`.
    pub fn name(self) -> &'static str {
        match self {
            Cat::Event => "event",
            Cat::Effect => "effect",
            Cat::Condition => "condition",
            Cat::Expression => "expression",
            Cat::Type => "type",
            Cat::Function => "function",
        }
    }

    /// File stem of the reference page (`docs/reference/<slug>.md`).
    pub fn slug(self) -> &'static str {
        match self {
            Cat::Event => "events",
            Cat::Effect => "effects",
            Cat::Condition => "conditions",
            Cat::Expression => "expressions",
            Cat::Type => "types",
            Cat::Function => "functions",
        }
    }

    pub fn title(self) -> &'static str {
        match self {
            Cat::Event => "Events",
            Cat::Effect => "Effects",
            Cat::Condition => "Conditions",
            Cat::Expression => "Expressions",
            Cat::Type => "Types",
            Cat::Function => "Functions",
        }
    }
}

/// One reference entry.
#[derive(Debug, Clone, Copy)]
pub struct Doc {
    /// Stable id, unique within its category.
    pub id: &'static str,
    pub name: &'static str,
    pub cat: Cat,
    /// Skript-style patterns. For effects and conditions, patterns that are in
    /// a registry are claimed by this entry; the rest are parsed by hand.
    pub patterns: &'static [&'static str],
    pub desc: &'static str,
    pub example: &'static str,
    pub since: &'static str,
    /// Guide page under `docs/`, without `.md`.
    pub page: &'static str,
}

/// A pattern registry (`*_PATTERNS` const) and its strings.
pub struct Registry {
    /// `module::CONST`, the same form the generator finds in the sources.
    pub name: &'static str,
    pub cat: Cat,
    pub patterns: Vec<&'static str>,
}

