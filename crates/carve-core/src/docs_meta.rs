/// `on join:` wrapper for examples that are only effect lines.
pub fn example_script(example: &str) -> String {
    let first = example.lines().next().unwrap_or("").trim_start();
    let top = ["on ", "command ", "every ", "function ", "options:"];
    if top.iter().any(|t| first.starts_with(t)) {
        example.to_string()
    } else {
        let body: Vec<String> = example.lines().map(|l| format!("    {l}")).collect();
        format!("on join:\n{}", body.join("\n"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn ids_unique_per_category() {
        let mut seen = HashSet::new();
        for d in DOCS {
            assert!(seen.insert((d.cat, d.id)), "duplicate doc id {}", d.id);
            assert!(!d.patterns.is_empty(), "{} has no pattern", d.id);
        }
    }

    #[test]
    fn examples_compile() {
        let mut bad = Vec::new();
        for d in DOCS.iter().filter(|d| !d.example.is_empty()) {
            let src = example_script(d.example);
            let c = crate::compile::compile_all(&[("example.sk".to_string(), src.clone())]);
            if !c.errors.is_empty() {
                bad.push(format!("{} {}: {:?}\n{src}", d.cat.name(), d.id, c.errors));
            }
        }
        assert!(
            bad.is_empty(),
            "examples that do not compile:\n{}",
            bad.join("\n\n")
        );
    }

    #[test]
    fn event_aliases_compile() {
        for d in DOCS.iter().filter(|d| d.cat == Cat::Event) {
            for p in d.patterns {
                if !p.starts_with("on ") || p.contains(['[', '(', '%', '<']) {
                    continue;
                }
                let src = format!("{p}:\n    set {{_x}} to 1");
                let c = crate::compile::compile_all(&[("e.sk".to_string(), src)]);
                assert!(c.errors.is_empty(), "{p}: {:?}", c.errors);
            }
        }
    }

    #[test]
    fn registries_compile() {
        assert!(crate::compile::check_registry().is_ok());
        assert!(registries().iter().all(|r| !r.patterns.is_empty()));
    }
}
